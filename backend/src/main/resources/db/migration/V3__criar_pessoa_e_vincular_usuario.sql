CREATE TABLE pessoa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf VARCHAR(11) UNIQUE,
    whatsapp VARCHAR(20),
    nome VARCHAR(160) NOT NULL,
    cep VARCHAR(8),
    logradouro VARCHAR(160),
    numero VARCHAR(20),
    complemento VARCHAR(100),
    bairro VARCHAR(100),
    cidade VARCHAR(100),
    uf VARCHAR(2),
    tipo_usuario VARCHAR(20) NOT NULL DEFAULT 'ALUNO',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pessoa_tipo_usuario_check
        CHECK (tipo_usuario IN ('ADMINISTRADOR', 'ALUNO')),
    CONSTRAINT pessoa_cpf_length_check
        CHECK (cpf IS NULL OR length(cpf) = 11),
    CONSTRAINT pessoa_cep_length_check
        CHECK (cep IS NULL OR length(cep) = 8)
);

ALTER TABLE pessoa
